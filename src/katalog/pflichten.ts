const NACH_ID = new Map(PFLICHTEN.map((p) => [p.id, p]))

export function pflicht(id: PflichtId): Pflicht {
  const p = NACH_ID.get(id)
  if (!p) throw new Error(`Unbekannte Pflicht ${id}`)
  return p
}

export function istPflichtId(id: string): id is PflichtId {
  return NACH_ID.has(id as PflichtId)
}

