const NACH_ID = new Map(FRAGEN.map((f) => [f.id, f]))

export function frage(id: FrageId): Frage {
  const f = NACH_ID.get(id)
  if (!f) throw new Error(`Unbekannte Frage ${id}`)
  return f
}

export function sichtbareFragen(p: Profil): Frage[] {
  return FRAGEN.filter((f) => f.sichtbar(p))
}

/** Nummer einer Frage für Texte wie „(Frage 4)“: F04 → 4. */
export function frageNummer(id: FrageId): number {
  return Number(id.slice(1))
}
